#!/usr/bin/env python3
"""Copy the compiled FAP and its actual SDK metadata into the static website."""

import hashlib
import json
from pathlib import Path
import struct


root = Path(__file__).resolve().parent
binary = root / "dist" / "vae_lightstick.fap"
data = binary.read_bytes()
if data[:6] != b"\x7fELF\x01\x01":
    raise ValueError("Expected a little-endian ELF32 FAP built by uFBT")

section_offset = struct.unpack_from("<I", data, 32)[0]
section_size, section_count, names_index = struct.unpack_from("<HHH", data, 46)
sections = [
    struct.unpack_from("<10I", data, section_offset + i * section_size)
    for i in range(section_count)
]
names_section = sections[names_index]
names = data[names_section[4] : names_section[4] + names_section[5]]
meta_section = next(
    section for section in sections
    if names[section[0] :].split(b"\0", 1)[0] == b".fapmeta"
)
magic, version, api, hardware = struct.unpack_from("<IIIh", data, meta_section[4])
if magic != 0x52474448 or version != 1 or hardware != 7:
    raise ValueError("Expected an F7 FAP with manifest version 1")

output = root.parent / "web" / "src" / "native"
output.mkdir(parents=True, exist_ok=True)
(output / binary.name).write_bytes(data)
manifest = {
    "protocol": 1,
    "api": f"{api >> 16}.{api & 0xFFFF}",
    "size": len(data),
    "md5": hashlib.md5(data).hexdigest(),
}
(output / "manifest.ts").write_text(
    "// Generated by native/package.py from the compiled FAP.\n"
    + "export const nativeApplication = "
    + json.dumps(manifest, ensure_ascii=False, indent=2)
    + " as const\n", encoding="utf-8"
)
print(f"Packaged {binary.name}: API {manifest['api']}, {len(data)} bytes")
